export function getChainlinkOracle(chainId: number, rawSymbol: string): string | undefined {
  const symbol = rawSymbol.toUpperCase()
  return CHAINLINK_ORACLES[chainId]?.[symbol]
}

export function getSupportedOracleTokens(chainId: number): string[] {
  const chainOracles = CHAINLINK_ORACLES[chainId]
  if (!chainOracles) return []
  return Object.keys(chainOracles)
}
